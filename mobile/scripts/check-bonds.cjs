/* Regression checks for desktop pricing conventions without native dependencies. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const loaded = { exports: {} };
const source = fs.readFileSync(path.join(process.cwd(), 'src/lib/bonds.ts'), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
new Function('exports', 'require', 'module', code)(loaded.exports, require, loaded);
const b = loaded.exports;
const bond = { id: 'test', kind: 'CDB', issuer: 'Bank', code: '', issueDay: 20250102, maturityDay: 20270102, indexer: 'fixed', rate: 12, quantity: 10, unitPrice: 1000 };
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`);
for (const [start, end, count] of [[20250303,20250305,0],[20250418,20250422,0],[20250619,20250621,1],[20261120,20261123,0],[20231120,20231121,1],[20250103,20250106,1],[20250106,20250103,0]]) assert.equal(b.businessDays(start, end), count);
assert.equal(b.valueBond(bond, null, 20250101), null);
assert.equal(b.valueBond(bond, null, bond.issueDay).net, 10000);
const fixed = b.valueBond(bond, null, 20260102);
close(fixed.gross, 10000 * 1.12 ** (b.businessDays(bond.issueDay, 20260102) / 252));
close(fixed.incomeTax, fixed.gain * .175);
close(fixed.net, fixed.gross - fixed.incomeTax);
assert.equal(b.valueBond(bond, null, 20280102).gross, b.valueBond(bond, null, bond.maturityDay).gross);
assert.equal(b.valueBond(bond, null, bond.maturityDay).atMaturity, undefined);
assert.equal(b.valueBond({ ...bond, kind: 'LCA' }, null, 20260102).incomeTax, 0);
for (const kind of ['LCA','LCI','CRI','CRA','Debênture incentivada']) assert.ok(b.isTaxExempt(kind));
for (const kind of ['CDB','LC','Debênture']) assert.ok(!b.isTaxExempt(kind));
for (const [days, rate] of [[180,.225],[181,.2],[360,.2],[361,.175],[720,.175],[721,.15]]) assert.equal(b.incomeTaxRate(days), rate);
for (const [days, rate] of [[0,1],[1,.96],[29,.03],[30,0],[31,0]]) assert.equal(b.iofRate(days), rate);
const early = b.valueBond(bond, null, 20250103);
close(early.iof, early.gain * .96);
assert.equal(b.valueBond({ ...bond, indexer: 'cdi' }, null, 20260102), null);
const rates = { cdi: [{ day: 20250102, rate: .05 }, { day: 20250103, rate: .06 }], ipca: [{ day: 20241201, rate: .5 }, { day: 20250101, rate: .6 }] };
const cdiBond = { ...bond, indexer: 'cdi', rate: 110 };
close(b.valueBond(cdiBond, rates, 20250106).gross, 10000 * (1 + 1.1 * .0005) * (1 + 1.1 * .0006));
close(b.valueBond(cdiBond, rates, 20250107).gross, 10000 * (1 + 1.1 * .0005) * (1 + 1.1 * .0006) ** 2);
close(b.valueBond({ ...bond, indexer: 'cdiPlus', rate: 2 }, rates, 20250106).gross, 10000 * 1.0005 * 1.0006 * 1.02 ** (2 / 252));
close(b.valueBond({ ...bond, indexer: 'ipca', rate: 0 }, rates, 20250202).gross, 10050);
const leapBond = { ...bond, issueDay: 20240131, maturityDay: 20270131, indexer: 'ipca', rate: 0 };
const leapRates = { cdi: [], ipca: [{ day: 20231201, rate: 1 }, { day: 20240101, rate: 2 }, { day: 20240201, rate: 3 }] };
close(b.valueBond(leapBond, leapRates, 20240331).gross, 10000 * 1.02 * 1.03);
console.log('Bond checks passed: calendar, compounding, taxes, maturities, missing data and leap anniversaries.');

